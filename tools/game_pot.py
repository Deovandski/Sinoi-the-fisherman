#!/usr/bin/env python3
"""Write game/i18n/messages.pot: every player-visible English string in the game (#2).

    python3 tools/game_pot.py          # rewrite game/i18n/messages.pot
    python3 tools/game_pot.py --check  # exit 1 if it's out of date (CI)

The POT is the English source for the game's translations (gettext, which
Godot reads natively). Translations go in game/i18n/<lang>.po later; making
them from this file keeps every existing translation and marks only new or
changed strings.

What it collects
- From game/scripts/**/*.gd: the string literal in tr("…"), tr_n("…", "…", n),
  TranslationServer.translate("…") and translate_plural("…", "…", n). Strings
  built at run time can't be found, so always pass tr() a literal (format it
  after: tr("Caught %d") % n).
- From game/data/*.json, the fields the game shows through tr(): fish names,
  regions, descriptions and lore; quality names; fight mode names and hints;
  ball names (as "%d sapphire" / "%d sapphires", see balls.gd); the support text.
The file has no creation date, so it only changes when the strings do.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GAME = ROOT / "game"
OUT = GAME / "i18n" / "messages.pot"
LIT = r'"((?:[^"\\\n]|\\.)*)"'
CALLS = [
    (re.compile(r"\btr\(\s*" + LIT + r"\s*\)"), False),
    (re.compile(r"\bTranslationServer\.translate\(\s*" + LIT + r"\s*\)"), False),
    (re.compile(r"\btr_n\(\s*" + LIT + r"\s*,\s*" + LIT), True),
    (re.compile(r"\bTranslationServer\.translate_plural\(\s*" + LIT + r"\s*,\s*" + LIT), True),
]


def po_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def collect() -> dict:
    """(msgid, msgid_plural or None) -> list of reference lines. msgids are PO-escaped."""
    found: dict = {}

    def add(msgid, plural, ref):
        if msgid:
            found.setdefault((msgid, plural), []).append(ref)

    for path in sorted((GAME / "scripts").rglob("*.gd")):
        rel = path.relative_to(GAME).as_posix()
        for number, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
            if line.lstrip().startswith("#"):
                continue
            for pattern, plural in CALLS:
                for m in pattern.finditer(line):
                    # GDScript and gettext escape strings the same way (\n, \", \\), so the literal is the msgid.
                    add(m.group(1), m.group(2) if plural else None, f"#: {rel}:{number}")

    def data(name):
        return json.loads((GAME / "data" / name).read_text(encoding="utf-8"))

    fish = data("fish.json")
    for f in fish.get("fish", []):
        for key in ("name", "region", "description", "lore"):
            if f.get(key):
                add(po_escape(f[key]), None, f"#. data/fish.json: {f['id']}.{key}")
    for q in fish.get("rewards", {}).get("quality_names", []):
        add(po_escape(q), None, "#. data/fish.json: rewards.quality_names")
    for m in data("fight_modes.json").get("modes", []):
        for key in ("name", "hint"):
            if m.get(key):
                add(po_escape(m[key]), None, f"#. data/fight_modes.json: {m['id']}.{key}")
    for b in data("balls.json").get("balls", []):
        if b.get("pearls", 1) > 1:
            add(po_escape(f"%d {b['name']}"), po_escape(f"%d {b['name']}s"), f"#. data/balls.json: {b['name']} (count)")
    support = data("credits.json").get("support_text")
    if support:
        add(po_escape(support), None, "#. data/credits.json: support_text")
    return found


def render(found: dict) -> str:
    out = [
        "# Sinoi the Fisherman: every player-visible string of the game, in English.",
        "# Generated by tools/game_pot.py; don't edit by hand. Names are written by sound,",
        "# never translated: see i18n/<lang>/glossary.json and CLAUDE.md, \"Translations\".",
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: Sinoi the Fisherman\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        "",
    ]
    for (msgid, plural), refs in found.items():
        out += [r for r in refs if r.startswith("#.")]
        out += [r for r in refs if r.startswith("#:")]
        if "%" in msgid:
            out.append("#, c-format")
        out.append(f'msgid "{msgid}"')
        if plural is None:
            out.append('msgstr ""')
        else:
            out += [f'msgid_plural "{plural}"', 'msgstr[0] ""', 'msgstr[1] ""']
        out.append("")
    return "\n".join(out)


def main() -> None:
    text = render(collect())
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--check" in sys.argv[1:]:
        if text != old:
            sys.exit("game/i18n/messages.pot is out of date: run python3 tools/game_pot.py and commit it.")
        print("game/i18n/messages.pot is up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(collect())} strings")


if __name__ == "__main__":
    main()
